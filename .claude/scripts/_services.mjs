// ═══ Разработка сайта (DEV) ═══
// Формула калькулятора MK (живой сайт сайты-марка.рф, компонент V6Calculator), ступени «скидки за объем»
// с полом: ставка ступени на весь объем, но не дешевле верхней границы предыдущей ступени (без провалов
// цены на 11, 21 и 51 странице).
export const DEV = {
  block_price: 6000,
  home_blocks_default: 10,
  home_blocks_min: 5,
  home_blocks_max: 20,
  prototype: { landing: 20000, multipage: 25000 },
  page_tiers: [
    { upTo: 10, rate: 5000 },
    { upTo: 20, rate: 4000 },
    { upTo: 50, rate: 3000 },
    { upTo: 100, rate: 2500 },
  ],
  pages_max: 100,
  deadline: { landing: "от 1 недели", multipage: "около 1 месяца" },
  hosting_year: 6000,
  quiz: 10000,
};

export function devSubpagesPrice(pages) {
  const n = Math.max(0, Math.min(DEV.pages_max, Math.round(Number(pages) || 0)));
  if (n === 0) return 0;
  let prevCap = 0;
  for (const tier of DEV.page_tiers) {
    if (n <= tier.upTo) return Math.max(n * tier.rate, prevCap);
    prevCap = Math.max(tier.upTo * tier.rate, prevCap);
  }
  return Math.max(n * DEV.page_tiers[DEV.page_tiers.length - 1].rate, prevCap);
}

// Цена базы разработки. format: "landing" | "multipage". Возврат: {total, parts[]}.
export function devPrice({ format = "multipage", pages = 0, home_blocks } = {}) {
  const fmt = format === "landing" ? "landing" : "multipage";
  let blocks = Math.round(Number(home_blocks) || DEV.home_blocks_default);
  blocks = Math.max(DEV.home_blocks_min, Math.min(DEV.home_blocks_max, blocks));
  const home = blocks * DEV.block_price;
  const proto = DEV.prototype[fmt];
  const sub = fmt === "landing" ? 0 : devSubpagesPrice(pages);
  // Больше DEV.pages_max подстраниц формула не считает: цена - за pages_max, подпись и pages - по тому же числу,
  // остальное - «по расчету» (pages_requested - сколько просили).
  const requested = Math.max(0, Math.round(Number(pages) || 0));
  const counted = Math.min(DEV.pages_max, requested);
  const over = fmt === "multipage" && requested > DEV.pages_max;
  const parts = [
    { label: `Главная страница: ${blocks} блоков`, price: home },
    { label: "Прототип с текстами до дизайна", price: proto },
  ];
  if (fmt === "multipage") {
    parts.push({
      label: over
        ? `Подстраницы: ${counted} шт. (по плану ${requested}; больше ${DEV.pages_max} - по расчету)`
        : `Подстраницы: ${counted} шт.`,
      price: sub,
    });
  }
  return {
    format: fmt, home_blocks: blocks, pages: fmt === "landing" ? 0 : counted,
    pages_requested: fmt === "landing" ? 0 : requested, pages_over_max: over,
    total: home + proto + sub, parts, prototype_price: proto,
  };
}

